using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace PhotinoNetUtils.Generators;

/// <summary>
///     Turns the keys of the embedded <c>.jsonc</c> translation files (added as
///     <c>AdditionalFiles</c>) into constants, so a call site reads
///     <c>Localization.Get(LocalizationKeys.ErrorOnlyVrchatLinks)</c> and a renamed key breaks the
///     build instead of the interface.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class LocalizationKeyGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var keys = context.AdditionalTextsProvider
            .Where(static file => LocalizationKeys.IsTranslationFile(file.Path))
            .Select(static (file, token) => LocalizationKeys.Read(file.GetText(token)?.ToString()).ToArray())
            .Collect();

        var rootNamespace = context.AnalyzerConfigOptionsProvider.Select(static (options, _) =>
            options.GlobalOptions.TryGetValue("build_property.RootNamespace", out var ns) ? ns : "");

        context.RegisterSourceOutput(keys.Combine(rootNamespace), static (output, input) =>
            Emit(output, input.Left, input.Right));
    }

    private static void Emit(SourceProductionContext context, ImmutableArray<string[]> files, string rootNamespace)
    {
        var keys = files
            .SelectMany(file => file)
            .Distinct(StringComparer.Ordinal)
            .OrderBy(key => key, StringComparer.Ordinal)
            .ToArray();

        if (keys.Length == 0)
            return;

        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine("#nullable enable");

        var indent = "";

        if (rootNamespace.Length > 0)
        {
            builder.AppendLine($"namespace {rootNamespace}");
            builder.AppendLine("{");
            indent = "    ";
        }

        builder.AppendLine($"{indent}/// <summary>Every key shipped in the embedded translation files.</summary>");
        builder.AppendLine($"{indent}internal static class LocalizationKeys");
        builder.AppendLine($"{indent}{{");

        foreach (var (name, key) in LocalizationKeys.Identify(keys))
            builder.AppendLine($"{indent}    public const string {name} = {Literal(key)};");

        builder.AppendLine($"{indent}}}");

        if (rootNamespace.Length > 0)
            builder.AppendLine("}");

        context.AddSource("LocalizationKeys.g.cs", SourceText.From(builder.ToString(), Encoding.UTF8));
    }

    private static string Literal(string value) =>
        Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(value, true);
}

/// <summary>The shared key reader behind the generator and the analyzer.</summary>
internal static class LocalizationKeys
{
    // Translation files are flat; a key is the first string on its line, before the colon.
    private static readonly Regex Entry = new(
        "^[ \t]*\"(?<key>(?:\\\\.|[^\"\\\\])*)\"[ \t]*:",
        RegexOptions.Multiline | RegexOptions.Compiled);

    public static bool IsTranslationFile(string path) =>
        path.EndsWith(".jsonc", StringComparison.OrdinalIgnoreCase);

    public static IEnumerable<string> Read(string? text) =>
        text is null ? Enumerable.Empty<string>() : FromText(text);

    public static IEnumerable<string> FromText(string text) =>
        Entry.Matches(text)
            .Cast<Match>()
            .Select(match => Regex.Unescape(match.Groups["key"].Value))
            .Where(key => key.Length > 0);

    /// <summary>Turns keys into unique PascalCase constants.</summary>
    public static IEnumerable<(string Name, string Key)> Identify(IEnumerable<string> keys)
    {
        var used = new HashSet<string>(StringComparer.Ordinal);

        foreach (var key in keys)
        {
            var name = Identifier(key);
            var candidate = name;
            var suffix = 2;

            while (!used.Add(candidate))
                candidate = name + suffix++;

            yield return (candidate, key);
        }
    }

    private static string Identifier(string key)
    {
        var builder = new StringBuilder();
        var upper = true;

        foreach (var character in key)
        {
            if (char.IsLetterOrDigit(character))
            {
                builder.Append(upper ? char.ToUpperInvariant(character) : character);
                upper = false;
            }
            else
            {
                upper = true;
            }
        }

        if (builder.Length == 0)
            return "Key";

        return char.IsDigit(builder[0]) ? "_" + builder : builder.ToString();
    }
}

// Builds `src/scripts.generated.ts` from the files a project offers for install, so the page always
// lists what the repository holds. The folder, extension and install scheme come from the project's
// `site.config.mjs`:
//
//   scripts: {directory: "../Lua", extension: ".lua", comment: "--", scheme: "checkurl://script?url=", branch: "master"}
//
// The first `-- ...` line (or whatever `comment` says) of a file is its one-line description.
//
// Run from the site directory: `node node_modules/@photino-net-utils/site/scripts/generate-scripts.mjs`.

import {existsSync} from "node:fs";
import {readFile, readdir, writeFile} from "node:fs/promises";
import path from "node:path";

const siteRoot = process.cwd();
const configPath = path.join(siteRoot, "site.config.mjs");

if (!existsSync(configPath)) {
    throw new Error(`No site.config.mjs in ${siteRoot}; the scripts generator reads the folder from it.`);
}

const {site} = await import(`file://${configPath.replace(/\\/g, "/")}?v=${Date.now()}`);
const settings = site.scripts;

if (!settings) {
    console.log("No scripts section in site.config.mjs, nothing to generate.");
    process.exit(0);
}

const directory = path.resolve(siteRoot, settings.directory ?? "../scripts");
const extension = settings.extension ?? ".lua";
const comment = settings.comment ?? "--";
const branch = settings.branch ?? "master";
const scheme = settings.scheme ?? "";
const folder = settings.folder ?? "scripts";
const repository = site.repository.replace(/^https:\/\/github\.com\//, "");

/** The first comment line of a file is its one-line description. */
function describe(source) {
    for (const line of source.split(/\r?\n/)) {
        const match = new RegExp(`^${comment}\\s+(.+)$`).exec(line);
        if (match) return match[1].trim();
    }

    return "";
}

const names = (await readdir(directory)).filter((name) => name.endsWith(extension)).sort();
const scripts = [];

for (const name of names) {
    const raw = `https://raw.githubusercontent.com/${repository}/${branch}/${folder}/${name}`;

    scripts.push({
        name,
        description: describe(await readFile(path.join(directory, name), "utf8")),
        source: raw,
        install: `${scheme}${encodeURIComponent(raw)}`,
    });
}

const output = path.join(siteRoot, "src", "scripts.generated.ts");

await writeFile(
    output,
    `// Generated by \`npm run generate\` from ${folder}; do not edit.
export interface ScriptEntry {
    name: string;
    description: string;
    source: string;
    install: string;
}

export const scripts: ScriptEntry[] = ${JSON.stringify(scripts, null, 4)};
`,
    "utf8",
);

console.log(`Generated ${scripts.length} script(s) into ${path.relative(siteRoot, output)}`);
